import GRDB

struct StoreRecord: SyncedRecord, Equatable {
    static let syncedTable = SyncedTable.stores

    var id: String
    var householdId: String
    var name: String
    var color: String?
    var createdAt: String?
    var updatedAt: String?
    var updatedBy: String?
    var deletedAt: String?
    var clientUpdatedAt: String?
    var serverSeq: Int64?
}

struct ProductRecord: SyncedRecord, Equatable {
    static let syncedTable = SyncedTable.products

    var id: String
    var householdId: String
    var name: String
    var category: String
    var defaultUnit: String?
    var pricePerKg: Double?
    var priceTotal: Double?
    var servings: Double?
    var servingsPerWeek: Double?
    var notes: String?
    var emoji: String?
    /// Storage path of the cover in `product-images`.
    var imagePath: String?
    /// `photo` (taken in the app) or `ai` (generated by an agent through the MCP); `nil` without a cover.
    var imageSource: String?
    var createdAt: String?
    var updatedAt: String?
    var updatedBy: String?
    var deletedAt: String?
    var clientUpdatedAt: String?
    var serverSeq: Int64?
}

struct ProductStoreRecord: SyncedRecord, Equatable {
    static let syncedTable = SyncedTable.productStores

    var id: String
    var householdId: String
    var productId: String
    var storeId: String
    var createdAt: String?
    var updatedAt: String?
    var updatedBy: String?
    var deletedAt: String?
    var clientUpdatedAt: String?
    var serverSeq: Int64?
}

struct ProductPhotoRecord: SyncedRecord, Equatable {
    static let syncedTable = SyncedTable.productPhotos

    var id: String
    var householdId: String
    var productId: String
    /// `<household>/<product>/<uuid>.<ext>` in the `product-images` bucket.
    var storagePath: String
    var width: Int?
    var height: Int?
    var position: Int
    var createdAt: String?
    var updatedAt: String?
    var updatedBy: String?
    var deletedAt: String?
    var clientUpdatedAt: String?
    var serverSeq: Int64?
}
