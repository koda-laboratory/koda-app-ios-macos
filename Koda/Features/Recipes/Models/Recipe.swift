import Foundation

/// Nutrient tags of a recipe (`recipes.nutrients`).
enum Nutrient: String, CaseIterable, Sendable, Codable {
    case fats
    case fiber
    case vegetables
    case protein
    case carbs
}

struct Recipe: Sendable, Equatable, Identifiable {
    let id: UUID
    let name: String
    let mealTypes: [MealSlot]
    let nutrients: [Nutrient]
    let timeMinutes: Int?
    /// Servings the ingredient quantities are written for.
    let servings: Double
    let steps: [String]
    let notes: String?
    /// Storage path of the cover (`recipe-images`), `nil` without one.
    let imagePath: String?
    let imageSource: RecipeImageSource?
    let emoji: String?
    let isFavorite: Bool

    /// Preparation time worth showing: imported recipes often carry 0 when the time was never filled in.
    var displayMinutes: Int? {
        guard let timeMinutes, timeMinutes > 0 else { return nil }
        return timeMinutes
    }
}

struct RecipeIngredient: Sendable, Equatable, Identifiable {
    let id: UUID
    let recipeID: UUID
    let productID: UUID
    let productName: String
    let productEmoji: String?
    let quantity: Double?
    let unit: String?
    let position: Int
}

/// "Pollo al horno" includes "Patatas al airfryer" (`servingsFactor` servings of the child per serving).
struct RecipeComponent: Sendable, Equatable, Identifiable {
    let id: UUID
    let parentRecipeID: UUID
    let childRecipeID: UUID
    let childRecipeName: String
    let childRecipeEmoji: String?
    let servingsFactor: Double
    let position: Int
}

struct RecipeDetail: Sendable, Equatable {
    let recipe: Recipe
    let ingredients: [RecipeIngredient]
    let components: [RecipeComponent]
    var photos: [RecipePhoto] = []

    /// What the "Fotos" strip and the viewer show: the gallery in order, preceded by the cover when it is not one of
    /// the photos (a cover generated by an agent).
    var gallery: [RecipeGalleryItem] {
        let cover = recipe.imagePath
        var items = photos.map { photo in
            RecipeGalleryItem(path: photo.storagePath, photoID: photo.id, isCover: photo.storagePath == cover)
        }
        if let cover, !items.contains(where: \.isCover) {
            items.insert(RecipeGalleryItem(path: cover, photoID: nil, isCover: true), at: 0)
        }
        return items
    }
}

/// Who made a recipe or product cover: a photo taken in the app or an image generated by an agent through the MCP.
enum RecipeImageSource: String, Sendable, Equatable {
    case photo
    case agent = "ai"
}

/// A photo of the recipe's gallery (`recipe_photos`); the bytes live in Storage at `storagePath`.
struct RecipePhoto: Sendable, Equatable, Identifiable {
    let id: UUID
    let recipeID: UUID
    let storagePath: String
    let width: Int?
    let height: Int?
    let position: Int
}

/// A link to a short video of the recipe (`recipe_links`), in the order the household added them.
struct RecipeLink: Sendable, Equatable, Identifiable {
    let id: UUID
    let recipeID: UUID
    let url: URL
    let position: Int

    /// The platform and account the URL points to.
    var info: RecipeLinkInfo {
        RecipeLinkPlatform.detect(url: url.absoluteString) ?? RecipeLinkInfo(platform: .other, account: nil, url: url)
    }
}

/// One image of the strip and the viewer (recipes and products). `photoID` is `nil` for a cover that is not in the
/// gallery.
struct RecipeGalleryItem: Sendable, Equatable, Identifiable {
    let path: String
    let photoID: UUID?
    let isCover: Bool

    var id: String { path }
}

/// Values to create (`id == nil`) or update a recipe's own fields.
struct RecipeInput: Sendable, Equatable {
    var id: UUID?
    var name: String
    var mealTypes: [MealSlot] = []
    var nutrients: [Nutrient] = []
    var timeMinutes: Int?
    var servings: Double = 2
    var steps: [String] = []
    var notes: String?
    var emoji: String?
    var isFavorite = false
}

struct RecipeIngredientInput: Sendable, Equatable {
    var recipeID: UUID
    var productID: UUID
    var quantity: Double?
    var unit: String?
}

/// How often and how recently a recipe was eaten (from `consumptions`, like the backend's `recipe_stats`).
struct RecipeStats: Sendable, Equatable {
    var timesEaten: Int
    var lastEatenOn: LocalDay?

    static let never = RecipeStats(timesEaten: 0, lastEatenOn: nil)

    func daysSinceLastEaten(today: LocalDay) -> Int? {
        guard let lastEatenOn else { return nil }
        let start = lastEatenOn.startDate(in: .gmt)
        let end = today.startDate(in: .gmt)
        return max(Int((end.timeIntervalSince(start) / 86_400).rounded()), 0)
    }
}

/// A recipe as the catalog lists it: searchable by ingredient and with its stats.
struct RecipeCatalogItem: Sendable, Equatable, Identifiable {
    let recipe: Recipe
    let ingredientNames: [String]
    let stats: RecipeStats

    var id: UUID { recipe.id }
}

/// An ingredient row of the recipe editor (`id == nil` for a new one).
struct RecipeIngredientDraft: Sendable, Equatable {
    var id: UUID?
    var productID: UUID
    var quantity: Double?
    var unit: String?
}

/// A sub-recipe row of the recipe editor (`id == nil` for a new one).
struct RecipeComponentDraft: Sendable, Equatable {
    var id: UUID?
    var childRecipeID: UUID
    var servingsFactor: Double
}

/// "Hace tiempo que no": recipes eaten at least once and not for a while, the longest ago first.
enum RecipeSuggestions {
    static func forgotten(
        _ items: [RecipeCatalogItem],
        today: LocalDay,
        minimumDays: Int = 14,
        limit: Int = 8
    ) -> [RecipeCatalogItem] {
        items
            .compactMap { item -> (RecipeCatalogItem, Int)? in
                guard let days = item.stats.daysSinceLastEaten(today: today), days >= minimumDays else { return nil }
                return (item, days)
            }
            .sorted { lhs, rhs in
                if lhs.1 != rhs.1 { return lhs.1 > rhs.1 }
                return lhs.0.recipe.name.localizedCaseInsensitiveCompare(rhs.0.recipe.name) == .orderedAscending
            }
            .prefix(limit)
            .map(\.0)
    }
}
