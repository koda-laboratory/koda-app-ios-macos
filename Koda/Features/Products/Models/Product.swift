import Foundation

struct Store: Sendable, Equatable, Identifiable {
    let id: UUID
    let name: String
    /// `#RRGGBB`, when set.
    let color: String?
}

struct Product: Sendable, Equatable, Identifiable {
    let id: UUID
    let name: String
    let category: ProductCategory
    let defaultUnit: String?
    let pricePerKg: Double?
    let priceTotal: Double?
    let servings: Double?
    let servingsPerWeek: Double?
    let notes: String?
    let emoji: String?
    /// Storage path of the cover (`product-images`), `nil` without one.
    var imagePath: String?
    var imageSource: RecipeImageSource?
    let storeIDs: Set<UUID>
}

/// Values to create (`id == nil`) or update a product.
struct ProductInput: Sendable, Equatable {
    var id: UUID?
    var name: String
    var category: ProductCategory = .food
    var defaultUnit: String?
    var pricePerKg: Double?
    var priceTotal: Double?
    var servings: Double?
    var servingsPerWeek: Double?
    var notes: String?
    var emoji: String?
    /// `nil` leaves the store links untouched.
    var storeIDs: Set<UUID>?
}

struct StoreInput: Sendable, Equatable {
    var id: UUID?
    var name: String
    var color: String?
}

/// A photo of the product's gallery (`product_photos`); the bytes live in Storage (`product-images`) at
/// `storagePath`.
struct ProductPhoto: Sendable, Equatable, Identifiable {
    let id: UUID
    let productID: UUID
    let storagePath: String
    let width: Int?
    let height: Int?
    let position: Int
}

/// A recipe that uses the product as an ingredient ("Se usa en").
struct ProductRecipeUsage: Sendable, Equatable, Identifiable {
    let recipeID: UUID
    let recipeName: String
    let quantity: Double?
    let unit: String?
    let timeMinutes: Int?

    var id: UUID { recipeID }

    /// Preparation time worth showing (imported recipes often carry 0).
    var displayMinutes: Int? {
        guard let timeMinutes, timeMinutes > 0 else { return nil }
        return timeMinutes
    }
}

/// Everything the product detail shows: the product, its stores, its gallery and the recipes that use it.
struct ProductDetail: Sendable, Equatable {
    let product: Product
    let stores: [Store]
    var photos: [ProductPhoto] = []
    var usages: [ProductRecipeUsage] = []

    /// The gallery in order, preceded by the cover when it is not one of the photos (a cover generated by an agent).
    var gallery: [RecipeGalleryItem] {
        let cover = product.imagePath
        var items = photos.map { photo in
            RecipeGalleryItem(path: photo.storagePath, photoID: photo.id, isCover: photo.storagePath == cover)
        }
        if let cover, !items.contains(where: \.isCover) {
            items.insert(RecipeGalleryItem(path: cover, photoID: nil, isCover: true), at: 0)
        }
        return items
    }
}
